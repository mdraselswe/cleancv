/**
 * Writes `src/features/templates/shared/catalogIconMarkup.ts`: the drawing of
 * each catalogue glyph beyond the original set, as plain SVG markup.
 *
 *   node scripts/build-icon-markup.mjs
 *
 * Lucide's components are client components. The PDF route renders a template
 * to a string on the server, and a client component cannot be called there -
 * the first deployment of the larger catalogue failed every export with
 * "Attempted to call the default export of lucide-react ... from the server".
 * Plain markup has no such boundary. Re-run this when a glyph is added to
 * `scripts/icon-glyphs.json` (catalogue key -> Lucide component name).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const require = createRequire(import.meta.url);
const lucide = require('lucide-react');

const glyphs = JSON.parse(readFileSync('scripts/icon-glyphs.json', 'utf8'));
const pairs = Object.entries(glyphs);

const lines = [];

for (const [key, name] of pairs) {
  const Glyph = lucide[name];
  if (!Glyph) throw new Error(`lucide-react has no ${name} (for ${key})`);

  const svg = renderToStaticMarkup(createElement(Glyph));
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  if (!inner || inner.includes('<svg')) throw new Error(`unexpected markup for ${key}`);

  lines.push(`  ${key.includes('-') ? `'${key}'` : key}: ${JSON.stringify(inner)},`);
}

writeFileSync(
  'src/features/templates/shared/catalogIconMarkup.ts',
  `/**
 * GENERATED by scripts/build-icon-markup.mjs - do not edit by hand.
 *
 * The inside of each catalogue glyph's 24x24 SVG. Plain strings, so a template
 * can draw them on the server without a client component.
 */
export const CATALOG_ICON_MARKUP: Record<string, string> = {
${lines.join('\n')}
};
`,
);

console.log(`${pairs.length} glyphs written`);
